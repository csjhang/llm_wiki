// Build config of the wiki-tool bundle. Run it with `npm run build:wiki-tool`.
//
// The bundle is one ES module that imports only node: built-ins. It is committed
// at plugins/llm-wiki/scripts/wiki-tool.mjs and the bundle test rebuilds it to
// compare bytes, so the output must not depend on the time, the machine, or the
// folder it is written to: no source maps, no minifier, no absolute paths.
// `npm run build:wiki-tool -- --file <path>` writes the bundle somewhere else.
import { fileURLToPath } from "node:url"
import { defineConfig } from "rolldown"

const repoRoot = fileURLToPath(new URL("../../", import.meta.url))

export default defineConfig({
  input: fileURLToPath(new URL("./src/main.ts", import.meta.url)),
  platform: "node",
  // Same alias as vite.config.ts and tsconfig.app.json, for files of src/lib.
  resolve: { alias: { "@": `${repoRoot}src` } },
  output: {
    format: "esm",
    file: fileURLToPath(new URL("../../plugins/llm-wiki/scripts/wiki-tool.mjs", import.meta.url)),
    sourcemap: false,
    minify: false,
    banner: "// Generated by `npm run build:wiki-tool` from tools/wiki-tool/src. Do not edit.",
  },
})
